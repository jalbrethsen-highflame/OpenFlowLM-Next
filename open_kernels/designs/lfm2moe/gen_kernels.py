"""Generate the kernel TUs of the LFM2-MoE designs (one extern "C" entry per file).

    python gen_kernels.py            # for OPEN_KERNELS_SPEC (an lfm2moe spec)

The mixer dispatches are dx.py / cx.py, whose TUs are the dense recipe's (designs/dense,
generated by its own gen_kernels.py, which this runs first). The rest is the routed-expert
block, `ex.py`, whose main cores hold:

    ex_px   xm (bf16, one 4 KB x element per 2048 values) -> the K=HID table at tab + 0
    ex_ph   the expert hidden h (f32, H_ELEMS x elements) -> the K=FF table at tab + H_TAB_OFF
    ex_gy   a 64-row band (K = HID) into a y element (lm.py's mixer stages)
    ex_gu   a 64-row up / gate band (K = HID) into ms + dst (u at MS_U, g at MS_G)
    ex_gd   down band j (K = FF) into ms + MS_YD + 64 j
    ex_hdr  the w-stream header: mode 0 = the routing record, 1 = this core's residual rows
    ex_act  h band = silu(g) * u -> one f32 y element
    ex_acc  slot >= 0: acc = (slot == 0 ? 0 : acc) + w[slot] * yd;  slot < 0: acc = xres + acc
    ex_out  y element j = acc rows 64 j .. 64 j + 63

Every GEMV TU is the f32-scale (GGUF-direct) build: -DGEMV_Q4_SCALES_F32=1 comes from ex.py's
compile flags, so the chunk constants in gemv_q4.h are the 6144-byte ones.

Scratch `ms` (floats): rw[32] @MS_RW | xr[ROWS_PC] @MS_XR | acc[ROWS_PC] @MS_ACC |
u[64] @MS_U | g[64] @MS_G | yd[ROWS_PC] @MS_YD.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))          # open_kernels/
from recipes.qwen36moe import ELEM, ROUT_IDX_OFF  # noqa: E402


def files(R) -> dict[str, str]:
    M = R.moe
    hdr = f'''#define GEMV_PER_CALL {M.PER_CALL}
#include "gemv_q4.h"
'''
    nbx = ELEM // 2 // 32                 # bf16 blocks of 32 in one 4 KB x element
    nbh = ELEM // 4 // 32                 # f32 blocks of 32 in one 4 KB x element
    return {
        "ex_gu.cc": hdr + f'''// A 64-row up / gate band (K = {M.HID}, {M.PB_H} chunks, rs 2) into ms + dst.
extern "C" {{
void ex_gu(const uint8_t *__restrict t, const uint8_t *__restrict tab, float *__restrict ms,
           int32_t group, int32_t dst) {{
  gemv_q4_pool_group_rt(t, tab, (unsigned)group, ms + dst, {M.PB_H}u, 2u);
}}
}}
''',
        "ex_gy.cc": hdr + f'''// A 64-row projection band (K = {M.HID}, {M.PB_H} chunks, rs 2) into its y element: the mixer
// stages of the merged layer image (lm.py), whose every projection is K = hidden.
extern "C" {{
void ex_gy(const uint8_t *__restrict t, const uint8_t *__restrict tab, float *__restrict y, int32_t group) {{
  gemv_q4_pool_group_rt(t, tab, (unsigned)group, y, {M.PB_H}u, 2u);
}}
}}
''',
        "ex_gd.cc": hdr + f'''// Down band j (K = {M.FF}, {M.PB_F} chunks, rs 2) against h's table at tab + {M.H_TAB_OFF}
// into ms + {M.MS_YD} + 64 j.
extern "C" {{
void ex_gd(const uint8_t *__restrict t, const uint8_t *__restrict tab, float *__restrict ms,
           int32_t group, int32_t j) {{
  gemv_q4_pool_group_rt(t, tab + {M.H_TAB_OFF}, (unsigned)group, ms + {M.MS_YD} + 64 * j, {M.PB_F}u, 2u);
}}
}}
''',
        "ex_px.cc": f'''// xm element i (bf16, {nbx} blocks of 32 per 4 KB) -> the K={M.HID} table at tab + 0.
#include "gemv_q4.h"

extern "C" {{
void ex_px(const bfloat16 *__restrict x, uint8_t *__restrict tab, int32_t i) {{
  const unsigned total = {M.HID // 32}u, b0 = {nbx}u * (unsigned)i;
  const unsigned nb = (b0 + {nbx}u <= total) ? {nbx}u : total - b0;
  gemv_q4_prep_blocks(x, tab, {M.HID}u, b0, nb);
}}
}}
''',
        "ex_ph.cc": f'''// h element i (f32, {nbh} blocks of 32 per 4 KB; the fifo types it bf16) -> the K={M.FF} table
// at tab + {M.H_TAB_OFF}, past xm's.
#include "gemv_q4.h"

extern "C" {{
void ex_ph(const bfloat16 *__restrict e, uint8_t *__restrict tab, int32_t i) {{
  const unsigned total = {M.FF // 32}u, b0 = {nbh}u * (unsigned)i;
  const unsigned nb = (b0 + {nbh}u <= total) ? {nbh}u : total - b0;
  gemv_q4_prep_f32_blocks((const float *)e, tab + {M.H_TAB_OFF}, {M.FF}u, b0, nb);
}}
}}
''',
        "ex_hdr.cc": f'''// The w-stream header, two {M.CALL_BYTES} B elements per core:
//   mode 0: the routing record -> rw = floats {ROUT_IDX_OFF // 4} .. {ROUT_IDX_OFF // 4 + 31} (idx[8], then w[e] at rw[8 + e])
//   mode 1: this core's {M.ROWS_PC} residual rows (f32) -> xr
#include "vecmath.h"

extern "C" {{
void ex_hdr(const uint8_t *__restrict e, float *__restrict ms, int32_t mode) {{
  if (mode == 0) {{
    aie::store_v(ms + {M.MS_RW}, aie::load_v<32>((const float *)(e + {ROUT_IDX_OFF})));
  }} else {{
    const float *__restrict xrs = (const float *)e;
    float *__restrict xr = ms + {M.MS_XR};
#pragma clang loop unroll(disable)
    for (unsigned j = 0; j < {M.ROWS_PC}; j += 32)
      aie::store_v(xr + j, aie::load_v<32>(xrs + j));
  }}
}}
}}
''',
        "ex_act.cc": f'''// h band = silu(g) * u for one 64-row band (ms: u @{M.MS_U}, g @{M.MS_G}) -> one f32 y element;
// the bf16 rounding happens in the consumer's table prep.
#include "vecmath.h"

extern "C" {{
void ex_act(const float *__restrict ms, float *__restrict h) {{
  aie::set_rounding(aie::rounding_mode::conv_even);
  const float *__restrict u = ms + {M.MS_U};
  const float *__restrict g = ms + {M.MS_G};
#pragma clang loop unroll(disable)
  for (unsigned j = 0; j < 64; j += 32)
    aie::store_v(h + j, fmul32(vsiluN<32>(aie::load_v<32>(g + j)), aie::load_v<32>(u + j)));
}}
}}
''',
        "ex_acc.cc": f'''// slot >= 0: acc = (slot == 0 ? 0 : acc) + w[slot] * yd   (the routed weight, rw[8 + slot])
// slot < 0:  acc = xres + acc                             (the block output)
// ms: rw @{M.MS_RW}, xr @{M.MS_XR}, acc @{M.MS_ACC}, yd @{M.MS_YD}. No scalar float ops (soft-float library):
// the weight multiplies as a bf16 hi/lo split, three MACs (moe_accfin's form).
#include "vecmath.h"

extern "C" {{
void ex_acc(float *__restrict ms, int32_t slot) {{
  aie::set_rounding(aie::rounding_mode::conv_even);
  const float *__restrict rw = ms + {M.MS_RW};
  const float *__restrict xr = ms + {M.MS_XR};
  float *__restrict acc = ms + {M.MS_ACC};
  const float *__restrict y = ms + {M.MS_YD};
  const bool close = slot < 0;
  v32b wh, wl;
  split32(aie::broadcast<float, 32>(close ? 0.f : rw[8 + slot]), wh, wl);
#pragma clang loop unroll(disable)
  for (unsigned j = 0; j < {M.ROWS_PC}; j += 32) {{
    accf32 a;
    if (close)
      a.from_vector(fadd32(aie::load_v<32>(xr + j), aie::load_v<32>(acc + j)));
    else if (slot == 0)
      a = aie::zeros<accfloat, 32>();
    else
      a.from_vector(aie::load_v<32>(acc + j));
    if (!close) {{
      v32b yh, yl;
      split32(aie::load_v<32>(y + j), yh, yl);
      a = aie::mac(a, yh, wh);
      a = aie::mac(a, yh, wl);
      a = aie::mac(a, yl, wh);
    }}
    aie::store_v(acc + j, a.template to_vector<float>());
  }}
}}
}}
''',
        "ex_out.cc": f'''// y element j (64 floats) = rows 64 j .. 64 j + 63 of this core's {M.ROWS_PC}-row block output (acc @{M.MS_ACC}).
#include "vecmath.h"

extern "C" {{
void ex_out(const float *__restrict ms, float *__restrict y, int32_t j) {{
  const float *__restrict acc = ms + {M.MS_ACC};
  aie::store_v(y, aie::load_v<32>(acc + 64 * j));
  aie::store_v(y + 32, aie::load_v<32>(acc + 64 * j + 32));
}}
}}
''',
    }


def _dense_generate(R) -> int:
    """The mixer designs' TUs (designs/dense/*.cc) for the same spec."""
    p = HERE.parent / "dense" / "gen_kernels.py"
    s = importlib.util.spec_from_file_location("dense_gen_kernels", p)
    m = importlib.util.module_from_spec(s)
    s.loader.exec_module(m)
    return m.generate(R)


def generate(R, out: Path = HERE) -> int:
    """Write the TUs for recipe R (only files whose text changed); returns the count."""
    n = _dense_generate(R)
    fs = files(R)
    for name, src in fs.items():
        p = out / name
        if not p.is_file() or p.read_text(encoding="utf-8") != src:
            p.write_text(src, encoding="utf-8", newline="\n")
    return n + len(fs)


if __name__ == "__main__":
    from recipes.load import current_recipe
    print(f"{generate(current_recipe())} kernel files")
